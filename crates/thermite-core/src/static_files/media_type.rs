// only the last extension counts, so `.tar.gz` is a gzip file, where Python says tar
pub(super) fn guess(path: &Path) -> HeaderValue {
    let media_type = path
        .extension()
        .and_then(|extension| extension.to_str())
        .map(str::to_ascii_lowercase)
        .and_then(|extension| {
            MEDIA_TYPES
                .binary_search_by(|(known, _)| (*known).cmp(extension.as_str()))
                .ok()
        })
        .map_or("application/octet-stream", |index| MEDIA_TYPES[index].1);
    HeaderValue::from_static(media_type)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_every_text_type_names_its_charset() {
        assert!(MEDIA_TYPES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (extension, media_type) in MEDIA_TYPES {
            assert_eq!(
                media_type.starts_with("text/"),
                media_type.ends_with("; charset=utf-8"),
                "{extension}"
            );
            assert!(HeaderValue::from_str(media_type).is_ok(), "{extension}");
        }
    }

    #[test]
    fn guesses_from_the_last_extension_whatever_its_case() {
        for (path, media_type) in [
            ("index.html", "text/html; charset=utf-8"),
            ("app.min.JS", "text/javascript; charset=utf-8"),
            ("logo.svg", "image/svg+xml"),
            ("font.woff2", "font/woff2"),
            ("archive.tar.gz", "application/gzip"),
            ("Makefile", "application/octet-stream"),
            (".bashrc", "application/octet-stream"),
            ("data.unknown", "application/octet-stream"),
        ] {
            assert_eq!(guess(Path::new(path)), media_type, "{path}");
        }
    }
}
